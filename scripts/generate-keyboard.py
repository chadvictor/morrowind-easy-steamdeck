#!/usr/bin/env python3
"""Build C and Lua layout tables from one US keyboard specification."""
import json
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = json.loads((ROOT / "assets/keyboard-layout.json").read_text(encoding="utf-8"))["rows"]
actions = ("text", "backspace", "tab", "caps", "enter", "shift", "left",
           "space", "right", "home", "end", "delete", "close")
keys = []
for row_index, row in enumerate(rows):
    x = 0
    for key in row:
        label, value = key[:2]
        width = key[2] if len(key) > 2 else 1
        text = len(label) == 1
        action = "text" if text else value
        assert action in actions
        keys.append(dict(label=label, shifted=value if text else label, action=action,
                         row=row_index, x=x, width=width))
        x += width
    assert x == 15, (row_index, x)
assert len(keys) < 96

def quoted(value):
    # All labels are ASCII; JSON string escapes are accepted in C and Lua here.
    return json.dumps(value, ensure_ascii=True)

header = ["/* Generated by scripts/generate-keyboard.py; edit assets/keyboard-layout.json. */",
          "#ifndef MES_KEYBOARD_LAYOUT_H", "#define MES_KEYBOARD_LAYOUT_H",
          "enum mes_key_action { " + ", ".join("MES_KEY_" + a.upper() for a in actions) + " };",
          "struct mes_keyboard_key { const char *label; const char *shifted; enum mes_key_action action; int row; float x; float width; };",
          "static const struct mes_keyboard_key mes_keyboard_keys[] = {"]
lua = ["-- Generated by scripts/generate-keyboard.py; edit assets/keyboard-layout.json.", "return {"]
for k in keys:
    header.append("    {%s, %s, MES_KEY_%s, %d, %sf, %sf}," % (
        quoted(k["label"]), quoted(k["shifted"]), k["action"].upper(), k["row"],
        float(k["x"]), float(k["width"])))
    lua.append("    {label=%s, shifted=%s, action=%s, row=%d, x=%s, width=%s}," % (
        quoted(k["label"]), quoted(k["shifted"]), quoted(k["action"]), k["row"], k["x"], k["width"]))
header += ["};", f"#define MES_KEYBOARD_KEY_COUNT {len(keys)}", "#define MES_KEYBOARD_ROWS 5", "#endif", ""]
lua += ["}", ""]
(ROOT / "native/keyboard-layout.h").write_text("\n".join(header), encoding="utf-8", newline="\n")
lua_dir = ROOT / "assets/keyboard/scripts/mes"
lua_dir.mkdir(parents=True, exist_ok=True)
(lua_dir / "keyboard_layout.lua").write_text("\n".join(lua), encoding="utf-8", newline="\n")
files = ["mes_keyboard.omwscripts", "scripts/mes/keyboard.lua", "scripts/mes/keyboard_layout.lua"]
manifest = [f"{hashlib.sha256((ROOT / 'assets/keyboard' / name).read_bytes()).hexdigest()}  {name}\n" for name in files]
(ROOT / "assets/keyboard-files.sha256").write_text("".join(manifest), encoding="utf-8", newline="\n")
print(f"Generated {len(keys)} keys in {len(rows)} rows.")
